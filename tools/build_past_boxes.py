# 每行 (道具名, 数量, 权重)，顺序与公示图一致
def box(
    id: str, name: str, year: int, season: str, release: str, price: int,
    theme: str, desc: str, rows: list[tuple[str, int, int]],
) -> dict:
    half = price == 100
    return {
        "id": id,
        "name": name,
        "subtitle": f"往期礼盒 · {season}限定",
        "category": "half" if half else "normal",
        "category_name": "半价盒子" if half else "正常盒子",
        "price": price,
        "total_weight": sum(w for _, _, w in rows),
        "theme": theme,
        "year": year,
        "kind": "past",
        "released": release,
        "source": SOURCE,
        "description": desc,
        "bonus": (
            [{"key": "feather", "name": "雁翎", "kind": "item", "rarity": "rare", "qty": 10},
             {"key": "soul_1000", "name": "将魂", "kind": "item", "rarity": "epic", "qty": 1}]
            if half else
            [{"key": "feather", "name": "雁翎", "kind": "item", "rarity": "rare", "qty": 20},
             {"key": "soul_1000", "name": "将魂", "kind": "item", "rarity": "epic", "qty": 2}]
        ),
        "_rows": rows,
    }


