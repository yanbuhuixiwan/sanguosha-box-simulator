def skin_quality() -> dict[str, str]:
    """盒内动态皮肤的品质：查 wiki_skins.json（键「皮肤名·武将名」）。

    皮肤允许「传说」档（如明良千古·关羽），官方皮肤体系是 普通/精良/稀有/史诗/传说/限定；
    限定按史诗处理，空缺兜底为史诗。
    """
    path = ROOT / "image" / "官网素材" / "wiki_skins.json"
    out: dict[str, str] = {}
    if not path.exists():
        return out
    rows = json.loads(path.read_text(encoding="utf-8"))
    for r in rows:
        key = f"{r.get('skin')}·{r.get('hero')}"
        q = (r.get("quality") or "").strip()
        out[key] = {"传说": "legendary", "史诗": "epic", "限定": "epic",
                    "稀有": "rare", "精良": "fine", "普通": "common"}.get(q, "epic")
    return out


SKIN_QUALITY = skin_quality()


def norm_rarity(kind: str, name: str, rarity: str) -> str:
    """按品级规范修正：武将无传说，皮肤的传说档保留，道具传说一律降为史诗。"""
    if kind == "hero":
        return HERO_QUALITY.get(name, "epic")
    if kind == "skin":
        return SKIN_QUALITY.get(name.replace("动态包", ""), "epic")
    return "epic" if rarity == "legendary" else rarity


def py(text: str) -> str:
    """中文转拼音作 key：势·邓艾 -> shidengai"""
    clean = re.sub(r"[·\s]", "", text)
    return "".join(lazy_pinyin(clean)).replace("·", "").lower()


def norm_hero(name: str) -> str:
    """官方表里写「势·邓艾」，项目里统一成「势邓艾」"""
    return re.sub(r"(?<=[势谋界神友骥])·", "", name)


def norm_skin(name: str) -> str:
    """「龙年中秋*刘备动态包」-> 「龙年中秋·刘备动态包」"""
    n = name.replace("*", "·").replace("＊", "·")
    a, _, b = n.partition("·")
    if b and not b.endswith("动态包"):
        b += "动态包"
    return f"{a}·{b}" if b else a


def entry_of(raw_name: str, qty: int, weight: int) -> dict:
    """把公示表的一行转成卡池条目。"""
    if raw_name == "菜篮子":
        rarity = "rare" if qty >= 99 else "common"
        return {
            "key": "basket", "name": raw_name, "qty": qty, "weight": weight,
            "kind": "item", "rarity": rarity, "icon": "basket",
        }
    if raw_name == "史诗宝珠":
        key = ORB_QTY.get(qty, "orb_1")
        return {
            "key": key, "name": raw_name, "qty": qty, "weight": weight,
            "kind": "item", "rarity": "epic", "icon": "orb",
        }
    if raw_name in ITEMS:
        key, rarity, icon = ITEMS[raw_name]
        item = {
            "key": key, "name": raw_name, "qty": qty, "weight": weight,
            "kind": "item", "rarity": rarity,
        }
        if icon:
            item["icon"] = icon
        return item

    if "动态包" in raw_name or "*" in raw_name:
        name = norm_skin(raw_name)
        hero = name.split("·")[1].replace("动态包", "") if "·" in name else name
        return {
            "key": f"skin_{py(hero)}", "name": name, "qty": 1, "weight": weight,
            "kind": "skin", "rarity": norm_rarity("skin", name, "epic"), "icon": "skin",
        }

    name = norm_hero(raw_name)
    return {
        "key": f"hero_{py(name)}", "name": name, "qty": 1, "weight": weight,
        "kind": "hero", "rarity": norm_rarity("hero", name, "epic"), "icon": "hero",
    }


