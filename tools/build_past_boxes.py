# 老数据里没有年份/上线日期，补上才能和新礼盒一起按时间排序与分组
EXISTING_META = {
    "summer_2026": (2026, "2026-08-01", False),
    "anniversary_2026": (2026, "2026-07-04", False),
    "lingxin_2026": (2026, "2026-06-05", False),
}


def build(report: bool) -> None:
    raw = json.loads(DATA.read_text(encoding="utf-8"))
    # 凡是脚本里定义过的往期盒都以脚本为准，旧文件里的同名盒直接替换
    past_ids = {b["id"] for b in PAST_BOXES}
    others = [b for b in raw["boxes"] if b["id"] not in past_ids]
    for b in others:
        if b["id"] in EXISTING_META:
            year, released, past = EXISTING_META[b["id"]]
            b["year"], b["released"] = year, released
            # 两个分支都要写 kind：前端靠 `kind === 'past'` 区分「往期复刻 / 在售」，
            # 缺字段虽然能靠 `!== 'past'` 兜住，但数据里会出现 undefined，审计对不齐
            b["kind"] = "past" if past else "current"
            if past:
                # 归入往期后副标题也要跟着改，否则卡片上还写着「正常盒子」
                season = re.sub(r"^\d{4}年", "", b["name"]).replace("礼盒", "")
                b["subtitle"] = f"往期礼盒 · {season}限定"
                b.setdefault("source", SOURCE)

    built = []
    for spec in PAST_BOXES:
        rows = spec.pop("_rows")
        pool = [entry_of(n, q, w) for n, q, w in rows]
        total = sum(e["weight"] for e in pool)
        for e in pool:
            e["probability"] = round(e["weight"] / total * 100, 4)
        p_sum = round(sum(e["probability"] for e in pool), 2)
        assert total == spec["total_weight"], f"{spec['id']} 权重总和 {total} 与声明不符"
        assert abs(p_sum - 100) < 0.02, f"{spec['id']} 概率合计 {p_sum}"
        item = {k: v for k, v in spec.items() if k != "id"}
        built.append({"id": spec["id"], **item, "pool": pool})

        if report:
            tops = sorted(pool, key=lambda e: e["weight"])[:3]
            top_text = " / ".join(f"{t['name']} {t['probability']}%" for t in tops)
            print(
                f"{spec['year']} {spec['name']:<14} {spec['price']:>3} 元宝  "
                f"{len(pool):>2} 项  权重 {total:>5}  概率 {p_sum:.2f}%  顶级 {top_text}"
            )

    # 排序：年份倒序，同年按上线日期倒序；老的 5 只盒子里没有 year，按 2026 处理
    merged = others + built

    # 品级规范化：对全部礼盒（含在售盒）统一执行——
    # 武将无传说（wiki 品质角标），皮肤按 wiki 品质，道具里的传说降为史诗
    fixed = 0
    for b in merged:
        for e in b["pool"]:
            kind = e.get("kind", "item")
            if kind not in ("hero", "skin") and e.get("rarity") != "legendary":
                continue
            want = norm_rarity(kind, e["name"], e.get("rarity", "common"))
            if e.get("rarity") != want:
                e["rarity"] = want
                fixed += 1
    if report:
        print(f"品级规范化：修正 {fixed} 条（武将无传说 / 皮肤按 wiki 品质 / 道具传说降史诗）")
    merged.sort(key=lambda b: (b.get("year", 2026), b.get("released", "2026-12-31")), reverse=True)

    if report:
        print(f"\n现有 {len(others)} + 新增 {len(built)} = {len(merged)} 只礼盒")
        return

    DATA.write_text(
        json.dumps({"boxes": merged}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"写入 {DATA.name}：{len(merged)} 只礼盒（新增 {len(built)} 只）")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true", help="只校验并打印，不写文件")
    args = ap.parse_args()
    build(args.report)
    sys.exit(0)
